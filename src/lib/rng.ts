export function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function hash(s: string): number {
  let h = 1779033703;
  for (let i = 0; i < s.length; i++) {
    h = Math.imul(h ^ s.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return h >>> 0;
}

/** Seed per gameweek. Add ?seed=xyz in the URL to force custom luck (for demos). */
export const seedFor = (gw: number): number => {
  const q = typeof location !== 'undefined'
    ? new URLSearchParams(location.search).get('seed')
    : null;
  return hash(`${q ?? 'edge'}:gw${gw}`);
};